import logging
import json
import asyncio
from typing import List, Dict, Any, Optional
import urllib.request
from src.config.settings import settings

logger = logging.getLogger(__name__)


class NotificationService:
    """Formats and dispatches high-value vehicle deal alerts."""

    @staticmethod
    def format_deal_digest_markdown(deals: List[Dict[str, Any]]) -> str:
        """Create a clean markdown report of the top scored vehicle deals."""
        if not deals:
            return "No high-scoring deals found matching criteria today."

        lines = [
            f"# 🚗 TOP VEHICLE DEALS FOUND (Bay Area - {settings.search_radius_miles}mi Radius)",
            f"*Generated by Car Researcher Pipeline for Zip: {settings.search_zip_code}*",
            "",
        ]

        for i, deal in enumerate(deals[:10], 1):
            listing = deal.get("listing", {})
            score_data = deal.get("score_data", {})

            price = listing.get("price", 0)
            market_val = score_data.get("market_value", price)
            price_delta = score_data.get("price_delta", 0)
            deal_score = score_data.get("deal_score", 0.0)
            recommendation = score_data.get("recommendation", "GOOD_VALUE")

            title = listing.get("title") or f"{listing.get('year')} {listing.get('make')} {listing.get('model')}"
            mileage = f"{listing.get('mileage', 0):,}"
            dist = f"{listing.get('distance_miles', 0):.1f} mi" if listing.get("distance_miles") else "Bay Area"
            title_status = listing.get("title_status", "clean").upper()
            url = listing.get("url", "#")
            platform = listing.get("platform", "").upper()

            savings_str = f"-${abs(price_delta):,} below market" if price_delta < 0 else f"+${price_delta:,} above market"

            lines.extend([
                f"### {i}. [{title}]({url}) — **${price:,}**",
                f"- **Deal Score:** `{deal_score}/100` ({recommendation})",
                f"- **Market Valuation:** Estimated Fair Value `${market_val:,}` (**{savings_str}**)",
                f"- **Odometer:** {mileage} miles | **Proximity:** {dist} | **Title:** {title_status}",
                f"- **Platform:** {platform} | **Platform ID:** `{listing.get('platform_id')}`",
                "",
            ])

        return "\n".join(lines)

    @classmethod
    async def send_discord_alert(cls, markdown_content: str, webhook_url: Optional[str] = None) -> bool:
        """Send formatted alert to Discord webhook."""
        url = webhook_url or settings.discord_webhook_url
        if not url:
            logger.info("Discord webhook not configured; skipping dispatch.")
            return False

        payload = {
            "content": markdown_content[:1990], # Discord 2000-char message limit
        }
        data = json.dumps(payload).encode("utf-8")

        def _post() -> bool:
            req = urllib.request.Request(
                url,
                data=data,
                headers={"Content-Type": "application/json", "User-Agent": "CarResearcher/1.0"},
                method="POST",
            )
            try:
                with urllib.request.urlopen(req, timeout=10.0) as resp:
                    return resp.status in (200, 204)
            except Exception as e:
                logger.error(f"Failed to post to Discord webhook: {e}")
                return False

        return await asyncio.to_thread(_post)


# -------------------------------------------------------------
# Temporal Activity Wrapper
# -------------------------------------------------------------
async def send_daily_deals_notification_activity(deals: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Temporal activity to format and notify user of top daily vehicle deals."""
    service = NotificationService()
    markdown_report = service.format_deal_digest_markdown(deals)
    discord_sent = await service.send_discord_alert(markdown_report)

    return {
        "deals_count": len(deals),
        "markdown_report": markdown_report,
        "discord_sent": discord_sent,
    }
